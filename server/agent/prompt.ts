/** エージェントのスレッドで、プリセットのシステムプロンプトの後ろに足す（FR-005）。モデルに読ませる文で、画面には出さない */
export function agentSystemPrompt(workspace: string): string {
  return [
    `あなたはワークスペース ${workspace} の中で作業するコーディングエージェントです。`,
    "ツールでファイルを読み、必要なら書き換え、コマンドを実行して、利用者の指示を進めます。",
    "パスはワークスペースからの相対パスで指定します。ワークスペースの外は使えません。",
    "ファイルを書き換える前に read_file で今の中身を確かめます。",
    "作業が終わったら、ツールを呼ばずに結果を簡潔に報告します。",
  ].join("\n");
}
